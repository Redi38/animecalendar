/**
 * Порядок дней в списке «По дням»: сначала сегодняшний или ближайший следующий день и все после него,
 * затем уже прошедшие дни. Так список начинается с актуального без прокрутки.
 * days — даты «ГГГГ-ММ-ДД»; today — сегодняшняя дата в том же формате.
 */
export function orderDays(days, today) {
  const sorted = [...days].sort();
  return [...sorted.filter((d) => d >= today), ...sorted.filter((d) => d < today)];
}
